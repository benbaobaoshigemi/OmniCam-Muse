"""Lumix S9 PhotoStyles and Spektrafilm films for the master LMT: packer and reference renderer.

Both engines are ports of PhotonCamera-bjzhou (third_party/PhotonCamera-bjzhou) and take the same
scene input as its shared raw pipeline: white-balanced linear ProPhoto (D50) with 18 % grey = 0.18.
master_lmt.render_look builds that input from the verified X9U decode and feeds the output (linear
sRGB) through the same HDRTransform inverse as HNCS.

Lumix (raw/LumixToneAlgorithm.kt, LumixProfile.kt, LumixColorTemperature.kt, EquivalentCameraCalibration.kt)
  ProPhoto -> S9 white-balanced camera RGB through the S9 DCP ColorMatrix1/2 (A / D65) interpolated
  at the scene white, x style gain -> clamp [0, 1] -> per-channel 2048-point curve -> 33^3 low and
  high cubes (red fastest, trilinear) blended by highWeight = clamp((coord - 256) / 256) with the
  Kelvin -> coordinate knots 3000/5000/6500/7500 -> 256/512/618/725 (truncated) -> clamp [0, clip]
  -> floor(x * 4095) / 4095 -> sRGB decode.
  Exposure: PhotonCamera feeds S9 camera RGB at its scene scale. The scale here puts 18 % grey where
  S9 Standard renders it as sRGB 118/255 (the standard 18 % -> 118 camera convention; HNCS anchors
  18 % -> display 0.18 and Spektrafilm designs around 0.18, so all three share one exposure).
Spektrafilm (cpp/spektrafilm, tables generated by spektrafilm_driver.cpp)
  ProPhoto / 2.88 -> ProPhoto 1.8 encode -> 65^3 film LUT; negatives -> x 1 / 1.5 -> 65^3 print LUT
  (positives: the film LUT includes the scan) -> ProPhoto 1.8 decode -> linear ProPhoto.

All non-Log Lumix styles are included; Flat and Cinelike preserve their original output.
Basic (kind 12): only a transfer after the front stage.
  type 0 pass-through (sRGB), 1 Rec.709 OETF, 2 power gamma: the scene luma (P3) goes through the curve and the colour is
  scaled by the luma ratio (hue preserving); a channel above 1 scales the pixel down instead of clipping. A pixel is
  written as display code = curve(luma) and the HDRTransform decodes it with the sRGB EOTF.
  type 3 standard: the tone of Lightroom's rendering of a DNG with an Adobe Standard profile: the ACR3 default tone curve
  (the Adobe DNG SDK's dng_tone_curve_acr3_default, a linear result) after the HueSatMap, which the front stage already
  applied. The curve acts on the scene luma and the colour is scaled by the luma ratio like the other basic types, so the
  chroma ratios are kept: the SDK's per-channel RGBTone changes them (a 1.2 to 1.9 times larger chroma than the luma
  ratio on the same colour), which Lightroom's own engine does not show. The SDK's exposure ramp black point (Shadows
  5.0) is not applied: Lightroom does not apply it either. The scene is first scaled by a gain so that 18 % grey comes
  out at display 0.18 like every other engine of the master LMT (the curve alone would put it at 0.388):
  standard_gain_ev. Layout: curve u32 count + f32[count], f32 gain EV.

Licences: Lumix tables are Panasonic data; Spektrafilm code GPL-3.0, profiles / LUTs CC BY-SA 4.0.

Usage: python looks.py <spektrafilm table dir> <out dir>   (writes <out>/<id>.bin)
"""
