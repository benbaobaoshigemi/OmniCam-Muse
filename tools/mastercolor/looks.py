# S9 "Panasonic DC-S9 Adobe Standard.dcp": ColorMatrix1 (illuminant 17 = A), ColorMatrix2 (21 = D65).
S9_CM1 = np.array([1.2599, -0.7524, 0.072, -0.4116, 1.1989, 0.2399, -0.0184, 0.076, 0.698]).reshape(3, 3)
S9_CM2 = np.array([0.9983, -0.389, -0.0841, -0.418, 1.2164, 0.2263, -0.0249, 0.1139, 0.5766]).reshape(3, 3)
S9_IL1, S9_IL2 = 2856.0, 6504.0
LUMIX_GREY_SRGB = 118.0 / 255.0
FILM_IN_SCALE = 1.0 / 2.88
PRINT_GAIN = 1.0 / 1.5

D50 = np.array([0.96422, 1.0, 0.82521])
D65 = np.array([0.95047, 1.0, 1.08883])
BRADFORD = np.array([[0.8951, 0.2664, -0.1614], [-0.7502, 1.7135, 0.0367], [0.0389, -0.0685, 1.0296]])
PROPHOTO_TO_XYZ = np.array([[0.7976749, 0.1351917, 0.0313534], [0.2880402, 0.7118741, 0.0000857],
                            [0.0, 0.0, 0.8252100]])
SRGB_TO_XYZ = np.array([[0.4124564, 0.3575761, 0.1804375], [0.2126729, 0.7151522, 0.0721750],
                        [0.0193339, 0.1191920, 0.9503041]])
P3_TO_XYZ = np.array([[0.4865709, 0.2656677, 0.1982173], [0.2289746, 0.6917385, 0.0792869],
                      [0.0, 0.0451134, 1.0439444]])


def cat(src, dst):
    s, d = BRADFORD @ src, BRADFORD @ dst
    return np.linalg.inv(BRADFORD) @ np.diag(d / s) @ BRADFORD


SRGB_TO_P3 = np.linalg.inv(P3_TO_XYZ) @ SRGB_TO_XYZ
PROPHOTO_TO_P3 = np.linalg.inv(P3_TO_XYZ) @ cat(D50, D65) @ PROPHOTO_TO_XYZ


def white_xyz(t):
    """Same locus as master_core.cpp whiteXyz."""
    if t < 4000:
        x = -0.2661239e9 / t ** 3 - 0.2343589e6 / t ** 2 + 0.8776956e3 / t + 0.179910
        y = (-1.1063814 * x ** 3 - 1.34811020 * x ** 2 + 2.18555832 * x - 0.20219683 if t < 2222
             else -0.9549476 * x ** 3 - 1.37418593 * x ** 2 + 2.09137015 * x - 0.16748867)
    else:
        x = (-4.6070e9 / t ** 3 + 2.9678e6 / t ** 2 + 0.09911e3 / t + 0.244063 if t <= 7000
             else -2.0064e9 / t ** 3 + 1.9018e6 / t ** 2 + 0.24748e3 / t + 0.237040)
        y = -3.0 * x * x + 2.87 * x - 0.275
    return np.array([x / y, 1.0, (1 - x - y) / y])


def prophoto_to_s9(cct):
    """Linear ProPhoto (D50) -> S9 white-balanced camera RGB at the scene white (DNG convention)."""
    g = np.clip((1 / cct - 1 / S9_IL1) / (1 / S9_IL2 - 1 / S9_IL1), 0, 1)
    cm = S9_CM1 * (1 - g) + S9_CM2 * g
    white = white_xyz(cct)
    cam_to_xyz = cat(white, D50) @ np.linalg.inv(cm) @ np.diag(cm @ white)
    return np.linalg.inv(cam_to_xyz) @ PROPHOTO_TO_XYZ


def lumix_coordinate(kelvin):
    kp, cp = [3000.0, 5000.0, 6500.0, 7500.0], [256.0, 512.0, 618.0, 725.0]
    seg = 0 if kelvin < kp[1] else (1 if kelvin < kp[2] else 2)
    c = cp[seg] + (kelvin - kp[seg]) * (cp[seg + 1] - cp[seg]) / (kp[seg + 1] - kp[seg])
    return int(np.clip(c, 0, 65535))


def trilinear(table, v):
    """table [n][n][n][3] indexed [b][g][r]; v (..., 3) in [0, 1]."""
    n = table.shape[0]
    p = np.clip(v, 0, 1) * (n - 1)
    i0 = np.minimum(np.floor(p).astype(np.int64), n - 2)
    f = p - i0
    out = np.zeros(v.shape)
    for db in (0, 1):
        for dg in (0, 1):
            for dr in (0, 1):
                w = ((f[..., 0] if dr else 1 - f[..., 0]) * (f[..., 1] if dg else 1 - f[..., 1])
                     * (f[..., 2] if db else 1 - f[..., 2]))
                out += w[..., None] * table[i0[..., 2] + db, i0[..., 1] + dg, i0[..., 0] + dr]
    return out


def srgb_decode(e):
    return np.where(e < 0.04045, e / 12.92, ((e + 0.055) / 1.055) ** 2.4)


def pp_encode(x):
    x = np.maximum(x, 0)
    return np.where(x >= 0.001953125, x ** (1 / 1.8), 16 * x)


def pp_decode(x):
    x = np.clip(x, 0, 1)
    return np.where(x >= 0.03125, x ** 1.8, x / 16)


