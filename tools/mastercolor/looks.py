def read_psl1(path, kind, dim):
    b = path.read_bytes()
    assert b[:4] == b"PSL1" and b[4] == kind and struct.unpack("<i", b[5:9])[0] == dim, path
    fmt = b[9]
    count = dim if kind == 0 else dim ** 3 * 3
    return np.frombuffer(b[88:88 + count * (2 if fmt == 1 else 4)], "<f2" if fmt == 1 else "<f4").astype(np.float32)


class Lumix:
    kind = 1

    def __init__(self, style, grey=None):
        base = PHOTON / "lumix" / "s9" / f"lut_{style}"
        self.style = style
        self.curve = read_psl1(Path(f"{base}.bin"), 0, 2048).astype(np.float64)
        self.low = read_psl1(Path(f"{base}_low.bin"), 1, 33).astype(np.float64).reshape(33, 33, 33, 3)
        self.high = read_psl1(Path(f"{base}_high.bin"), 1, 33).astype(np.float64).reshape(33, 33, 33, 3)
        self.gain = 2.0 ** (-7.0 / 6.0 if style in ("cinelike_d2", "cinelike_v2") else 0.0)
        self.clip = 1.0
        self.grey = grey if grey is not None else lumix_grey()

    def render_camera(self, cam, cct):
        """S9 white-balanced camera RGB -> linear sRGB (LumixToneShader.applyEngineTone)."""
        hw = np.clip((lumix_coordinate(cct) - 256) / 256.0, 0, 1)
        cam = np.clip(cam * self.gain, 0, 1)
        shaped = np.interp(cam, np.linspace(0, 1, 2048), self.curve)
        enc = np.clip(trilinear(self.low, shaped) * (1 - hw) + trilinear(self.high, shaped) * hw, 0, self.clip)
        return srgb_decode(np.floor(enc * 4095) / 4095)

    def render(self, prophoto, cct):
        """Scene ProPhoto (18 % grey = 0.18) -> display-linear P3."""
        cam = prophoto @ prophoto_to_s9(cct).T * (self.grey / 0.18)
        return np.clip(self.render_camera(cam, cct) @ SRGB_TO_P3.T, 0, 1)


def lumix_grey():
    """S9 camera level that Standard renders as sRGB 118/255 (green channel, 5000 K); bisection."""
    std = Lumix.__new__(Lumix)
    Lumix.__init__(std, "standard", grey=1.0)
    lo, hi = 0.01, 0.5
    for _ in range(60):
        q = (lo + hi) / 2
        g = std.render_camera(np.array([[q, q, q]]), 5000.0)[0, 1]
        e = 12.92 * g if g < 0.0031308 else 1.055 * g ** (1 / 2.4) - 0.055
        lo, hi = (q, hi) if e < LUMIX_GREY_SRGB else (lo, q)
    return (lo + hi) / 2


class Film:
    kind = 2

    def __init__(self, film, paper, tables):
        load = lambda p: np.fromfile(p, "<f4").reshape(65, 65, 65, 4)[..., :3].astype(np.float64)
        self.film = load(Path(tables) / f"{film}_film.f32")
        self.print = load(Path(tables) / f"{film}_print.f32") if paper else None

    def render(self, prophoto, cct=None):
        r = trilinear(self.film, pp_encode(prophoto * FILM_IN_SCALE))
        if self.print is not None:
            r = trilinear(self.print, r * PRINT_GAIN)
        return np.clip(pp_decode(r) @ PROPHOTO_TO_P3.T, 0, 1)


