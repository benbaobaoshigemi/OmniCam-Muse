def acr3_curve():
    """ACR3 default tone curve: 1025 uniform samples over [0, 1]. The same table is in the DNG SDK (dng_render.cpp
    dng_tone_curve_acr3_default::Evaluate) and in Lightroom's libLrAndroid.so, bit for bit."""
    import re
    s = (PHOTON.parent / "java/com/hinnka/mycamera/raw/ACR3Curve.kt").read_text(encoding="utf-8")
    body = s[s.index("floatArrayOf(") + 13:s.index(")", s.index("floatArrayOf("))]
    curve = np.array([float(x.rstrip("f")) for x in re.findall(r"[0-9.]+f", body)])
    assert len(curve) == 1025 and curve[0] == 0 and curve[-1] == 1
    return curve


def standard_gain_ev(curve):
    """EV the scene needs before the ACR3 curve so that 18 % grey leaves it at display 0.18."""
    return float(np.log2(np.interp(0.18, curve, np.linspace(0, 1, len(curve))) / 0.18))


def pack_basic(kind, gamma):
    b = b"MCOLLOOK" + struct.pack("<IIIf", 1, 12, kind, gamma)
    if kind == 3:
        curve = acr3_curve()
        b += struct.pack("<I", len(curve)) + curve.astype("<f4").tobytes()
        b += struct.pack("<f", standard_gain_ev(curve))
    return b


def srgb_oetf(x):
    x = np.clip(x, 0, None)
    return np.where(x <= 0.0031308, 12.92 * x, 1.055 * x ** (1 / 2.4) - 0.055)


def render_basic(kind, gamma, prophoto, curve=None, gain_ev=0.0):
    """Scene ProPhoto (18 % grey = 0.18) -> display-linear P3 in [0, 1] through a transfer curve."""
    p3 = np.maximum(np.asarray(prophoto, np.float64) @ PROPHOTO_TO_P3.T, 0)
    if kind == 3:
        p3 = p3 * 2.0 ** gain_ev
    y = p3 @ P3_TO_XYZ[1]
    if kind == 3:
        t = np.interp(y, np.linspace(0, 1, len(curve)), curve)   # display-linear luma (the curve ends at its white)
        out = p3 * (t / np.maximum(y, 1e-12))[..., None]
        out = np.where((y > 0)[..., None], out, 0.0)
        return out / np.maximum(out.max(-1, keepdims=True), 1.0)
    if kind == 0:
        code = srgb_oetf(y)
    elif kind == 1:
        code = np.where(y < 0.018, 4.5 * y, 1.099 * np.maximum(y, 1e-12) ** 0.45 - 0.099)
    else:
        code = np.maximum(y, 0) ** (1 / gamma)
    t = srgb_decode(np.minimum(code, 1.0))
    out = p3 * (t / np.maximum(y, 1e-12))[..., None]
    out = np.where((y > 0)[..., None], out, 0.0)
    return out / np.maximum(out.max(-1, keepdims=True), 1.0)


class Packed:
    """Reference renderer reading a packed look file (what the device reads)."""

    def __init__(self, path):
        b = Path(path).read_bytes()
        assert b[:8] == b"MCOLLOOK"
        _, self.kind = struct.unpack("<II", b[8:16])
        at = 16
        if self.kind in (10, 11):
            import firmware_engines as F
            self.params = F.decode(self.kind, b)
        elif self.kind == 12:
            kind, gamma = struct.unpack("<If", b[at:at + 8])
            at += 8
            curve, gain_ev = None, 0.0
            if kind == 3:
                n = struct.unpack("<I", b[at:at + 4])[0]
                curve = np.frombuffer(b[at + 4:at + 4 + 4 * n], "<f4").astype(np.float64)
                gain_ev = struct.unpack("<f", b[at + 4 + 4 * n:at + 8 + 4 * n])[0]
                at += 8 + 4 * n
            assert at == len(b)
            self.params = (kind, gamma, curve, gain_ev)
        elif self.kind == 8:
            self.in_scale, self.print_gain = struct.unpack("<2f", b[at:at + 8]); at += 8
            stages = []
            for _ in range(2):
                n = struct.unpack("<I", b[at:at + 4])[0]; at += 4
                name = b[at:at + n].decode("ascii"); at += n
                stages.append(np.fromfile(Path(path).parent / "tables" / (name + ".u16"), "<u2")
                              .astype(np.float64).reshape(65, 65, 65, 3) / 65535 if name else None)
            self.film, self.print = stages
            self.kind = 2
        elif self.kind == 7:
            ev, il1, il2 = struct.unpack("<3f", b[at:at + 12]); at += 12
            cm1 = np.frombuffer(b[at:at + 36], "<f4").astype(np.float64).reshape(3, 3); at += 36
            cm2 = np.frombuffer(b[at:at + 36], "<f4").astype(np.float64).reshape(3, 3); at += 36
            words = np.frombuffer(b[at:at + 0x168 * 4], "<i4").astype(np.int64); at += 0x168 * 4
            atlas = np.frombuffer(b[at:at + 1024 * 324 * 4], "<i4").astype(np.int64); at += 1024 * 324 * 4
            has_icc = struct.unpack("<I", b[at:at + 4])[0]; at += 4
            icc = None
            if has_icc:
                grid, n, m = struct.unpack("<3I", b[at:at + 12]); at += 12
                f = lambda k: np.frombuffer(b[at:at + 4 * k], "<f4").astype(np.float64)
                inp = f(3 * n).reshape(3, n); at += 12 * n
                clut = f(3 * grid ** 3).reshape(grid, grid, grid, 3); at += 12 * grid ** 3
                out = f(3 * m).reshape(3, m); at += 12 * m
                x2t = f(9).reshape(3, 3); at += 36
                white = f(3); at += 12
                sizes = struct.unpack("<3I", b[at:at + 12]); at += 12
                trc = []
                for k in sizes:
                    trc.append(f(k)); at += 4 * k
                icc = dict(grid=grid, inp=inp, clut=clut, out=out, xyz_to_target=x2t, white=white, trc=trc)
            self.params = dict(engine_ev=ev, il1=il1, il2=il2, cm1=cm1, cm2=cm2, words=words, atlas=atlas, icc=icc)
        elif self.kind in (3, 4, 5):
            if self.kind == 3:
                self.params = dict(zip(("contrast", "hue"), struct.unpack("<2f", b[at:at + 8])))
            elif self.kind == 4:
                self.params = dict(zip(("black", "white", "toe", "shoulder"), struct.unpack("<4f", b[at:at + 16])))
            else:
                self.params = dict(zip(("black", "white"), struct.unpack("<2f", b[at:at + 8])))
        elif self.kind == 1:
            self.grey, self.gain, self.clip, il1, il2 = struct.unpack("<5f", b[at:at + 20]); at += 20
            at += 72
            take = lambda n: np.frombuffer(b[at:at + n * 2], "<f2").astype(np.float64)
            self.curve = take(2048); at += 4096
            self.low = take(33 ** 3 * 3).reshape(33, 33, 33, 3); at += 33 ** 3 * 6
            self.high = take(33 ** 3 * 3).reshape(33, 33, 33, 3)
        else:
            has_print, self.in_scale, self.print_gain = struct.unpack("<Iff", b[at:at + 12]); at += 12
            n = 65 ** 3 * 3
            take = lambda o: np.frombuffer(b[o:o + n * 2], "<u2").astype(np.float64).reshape(65, 65, 65, 3) / 65535
            self.film = take(at)
            self.print = take(at + n * 2) if has_print else None

    def render(self, prophoto, cct, param=None):
        """param: the key's look parameters (up to four, NaN / None = the file's default), clamped as master_core.cpp."""
        if self.kind in (10, 11):
            import firmware_engines as F
            return F.render(self.kind, self.params, prophoto, cct)
        if self.kind == 12:
            kind, gamma, curve, gain_ev = self.params
            if kind == 2 and param is not None and param[0] is not None and np.isfinite(param[0]):
                gamma = float(np.clip(param[0], 1.0, 4.0))
            return render_basic(kind, gamma, prophoto, curve, gain_ev)
        if self.kind == 7:
            return render_canon(self.params, prophoto, cct)
        if self.kind in (3, 4, 5):
            params = dict(self.params)
            for name, v, (lo, hi) in zip(PARAM_NAMES[self.kind], param if param is not None else [], PARAM_RANGES[self.kind]):
                if v is not None and np.isfinite(v):
                    params[name] = float(np.clip(v, lo, hi))
            return render_dt(self.kind, params, prophoto)
        if self.kind == 1:
            lx = Lumix.__new__(Lumix)
            lx.curve, lx.low, lx.high, lx.gain, lx.clip, lx.grey = (self.curve, self.low, self.high,
                                                                  self.gain, self.clip, self.grey)
            return Lumix.render(lx, prophoto, cct)
        fm = Film.__new__(Film)
        fm.film, fm.print = self.film, self.print
        return Film.render(fm, prophoto)


