# looks/<id>.bin, little endian:
#   char[8] "MCOLLOOK", u32 version 1, u32 kind (1 Lumix, 2 film)
#   Lumix: f32 grey, gain, clip, il1 K, il2 K, f32[9] CM1, f32[9] CM2, f16[2048] curve, f16[33^3*3] low, high
#   film:  u32 hasPrint, f32 inScale, printGain, u16[65^3*3] film (/65535), [u16[65^3*3] print]
def pack_lumix(style, grey):
    lx = Lumix(style, grey)
    b = bytearray(b"MCOLLOOK") + struct.pack("<II", 1, 1)
    b += struct.pack("<5f", grey, lx.gain, lx.clip, S9_IL1, S9_IL2)
    b += S9_CM1.astype("<f4").tobytes() + S9_CM2.astype("<f4").tobytes()
    for t in (lx.curve, lx.low, lx.high):
        h = t.astype("<f2")
        assert np.array_equal(h.astype(np.float64), t), "PSL1 data is exactly half precision"
        b += h.tobytes()
    return bytes(b)


def pack_film(film, paper, tables):
    f = Film(film, paper, tables)
    q = lambda t: np.round(np.clip(t, 0, 1) * 65535).astype("<u2").tobytes()
    b = bytearray(b"MCOLLOOK") + struct.pack("<II", 1, 2)
    b += struct.pack("<Iff", int(paper is not None), FILM_IN_SCALE, PRINT_GAIN) + q(f.film)
    if paper:
        b += q(f.print)
    return bytes(b)


