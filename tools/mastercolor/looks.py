def prophoto_to_camera(cm1, cm2, il1, il2, cct):
    """Linear ProPhoto (D50) -> white-balanced camera RGB of a DNG ColorMatrix pair at the scene white."""
    g = np.clip((1 / cct - 1 / il1) / (1 / il2 - 1 / il1), 0, 1)
    cm = cm1 * (1 - g) + cm2 * g
    white = white_xyz(cct)
    cam_to_xyz = cat(white, D50) @ np.linalg.inv(cm) @ np.diag(cm @ white)
    return np.linalg.inv(cam_to_xyz) @ PROPHOTO_TO_XYZ


def render_canon(p, prophoto, cct):
    import engines_canon as C
    cam = (prophoto * 2.0 ** p["engine_ev"]) @ prophoto_to_camera(p["cm1"], p["cm2"], p["il1"], p["il2"], cct).T
    return np.clip(C.canon(cam, p) @ SRGB_TO_P3.T, 0, 1)


