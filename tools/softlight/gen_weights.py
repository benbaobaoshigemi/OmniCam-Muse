"""Write app/src/main/cpp/soft_light_weights.h from the soft light experiment's pyramid weights.

The weights distil the simulated point spread of each filter (HDF, black mist) onto the blur
pyramid the camera runs (soft_light.cpp): per row of log2(focal length in pixels), per colour
channel, per pyramid level; level 0 is the image itself.

Usage: gen_weights.py [pyramid_weights.json]  (default: refs.SOFT_LIGHT / pyramid_weights.json)
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import refs  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "app/src/main/cpp/soft_light_weights.h"
FILTERS = (("kBlackMist", "黑柔"), ("kWhiteMist", "白柔"), ("kHdf", "HDF"))


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else refs.SOFT_LIGHT / "pyramid_weights.json"
    table = json.loads(src.read_text(encoding="utf-8"))
    l2 = table["log2_fpx"]
    step = l2[1] - l2[0]
    levels = table["levels"] + 1
    lines = [
        "// Generated by tools/softlight/gen_weights.py from the soft light experiment's pyramid_weights.json.",
        "#pragma once",
        "",
        f"constexpr int kSoftRows = {len(l2)};",
        f"constexpr int kSoftLevels = {levels};  // level 0 = the image, then {table['levels']} downsampled levels",
        f"constexpr float kSoftLog2First = {l2[0]:.4f}f;",
        f"constexpr float kSoftLog2Step = {step:.4f}f;",
        "",
        "struct SoftFilter {",
        "    float core[3];",
        "    float transmission[3];",
        "    float weights[kSoftRows][3][kSoftLevels];",
        "};",
        "",
    ]
    for ident, name in FILTERS:
        f = table["filters"][name]
        rows = []
        for row in f["weights"]:
            chans = ", ".join("{" + ", ".join(f"{w:.6e}f" for w in ch) + "}" for ch in row)
            rows.append(f"        {{{chans}}},")
        lines += [
            f"constexpr SoftFilter {ident} = {{",
            "    {" + ", ".join(f"{v:.6f}f" for v in f["core"]) + "},",
            "    {" + ", ".join(f"{v:.6f}f" for v in f["transmission"]) + "},",
            "    {",
            *rows,
            "    },",
            "};",
            "",
        ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(OUT)


if __name__ == "__main__":
    main()
