"""Write app/src/main/cpp/soft_light_curve.h: the master pipeline's neutral tone curve as 1D tables.

The soft light scatters scene light, but Meishe hands it the master LMT output (an HLG signal).
Along the grey axis that output is
    h = LMT_grey(builtin_gamma(lin))                  lin = sensor linear, 18 % grey = the code 0.3613
(tools/mastercolor/master_lmt.py documents the chain). LMT_grey is the mean grey curve of the
six stock master tables LMTLut0-5 (they differ by a few code values). Applied per channel, the
inverse gives scene light s (18 % grey = 0.18, sensor clip = S_MAX) from h, and the forward table
encodes the scattered light back.

Usage: gen_curve.py
"""
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import refs  # noqa: E402

OUT = ROOT / "app/src/main/cpp/soft_light_curve.h"
N = 1024


def main():
    gamma = np.load(ROOT / "tools/mastercolor/data/x9u_proproc_builtin_gamma.npy").astype(np.float64) / 1023.0
    code = np.minimum(gamma, 3178 / 4095)
    lin = np.arange(65536) / 65535.0
    grey_lin = np.interp(0.3613, code, lin)
    nodes = np.arange(64) / 63.0
    greys = []
    for n in range(6):
        lut = np.fromfile(refs.STOCK_ODM / f"odm/etc/camera/basictone/lmt/LMTLut{n}", "<f4").reshape(3, 64, 64, 64)
        greys.append([lut[0, k, k, k] for k in range(64)])
    grey = np.mean(greys, axis=0)

    s = lin / grey_lin * 0.18                        # scene light, 18 % grey = 0.18
    h = np.interp(code, nodes, grey)
    h = np.maximum.accumulate(h)                      # monotone for the inverse
    s_max = s[-1]
    # Forward: uniform in log2 s.
    lo = np.log2(s[1])
    hi = np.log2(s_max)
    fwd_s = 2.0 ** np.linspace(lo, hi, N)
    fwd = np.interp(fwd_s, s, h)
    # Inverse: uniform in h; flat parts of h take their first s.
    hs = np.linspace(0.0, 1.0, N)
    uniq_h, first = np.unique(h, return_index=True)
    inv = np.interp(hs, uniq_h, s[first])

    def table(name, values):
        body = ",\n".join("    " + ", ".join(f"{v:.6e}f" for v in values[i:i + 8]) for i in range(0, len(values), 8))
        return [f"constexpr float {name}[kSoftCurveN] = {{", body, "};", ""]

    lines = [
        "// Generated by tools/softlight/gen_curve.py: the master pipeline's neutral tone curve.",
        "#pragma once",
        "",
        f"constexpr int kSoftCurveN = {N};",
        f"constexpr float kSoftSceneMax = {s_max:.6f}f;   // sensor clip in scene light (18 % grey = 0.18)",
        f"constexpr float kSoftLog2SceneMin = {lo:.6f}f;",
        f"constexpr float kSoftLog2SceneMax = {hi:.6f}f;",
        f"constexpr float kSoftHlgMax = {h[-1]:.6f}f;   // HLG signal of the sensor clip",
        "",
        "// HLG signal (uniform 0..1) -> scene light.",
        *table("kSoftHlgToScene", inv),
        "// Scene light (uniform in log2 between the limits) -> HLG signal.",
        *table("kSoftSceneToHlg", fwd),
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(OUT, "grey lin", grey_lin, "s_max", s_max, "h(grey)", np.interp(0.18, s, h), "h max", h[-1])


if __name__ == "__main__":
    main()
